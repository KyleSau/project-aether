"""OpenFOAM case generator: axisymmetric (5-degree wedge) under/over-expanded exhaust plume.

Generates a ready-to-run case for the density-based compressible solver `rhoCentralFoam`
(Kurganov-Tadmor central scheme, suited to shock-containing supersonic jets) at a selected
flight condition. Inlet = nozzle exit plane with the Cantera-derived exit state; co-flowing
freestream at the vehicle's air-relative speed; ambient pressure/temperature from USSA-1976.

Status in this project: NOT CONNECTED (no OpenFOAM installation available). Nothing produced
by this module is ever displayed as solver data unless a run actually completes and its
output files are parsed by results.py.

Known modelling limitations of this first case (documented in docs/AETHER.md):
  * single calorically-perfect gas everywhere (exhaust gamma/MW from Cantera); air entrainment
    with different gamma is not represented (rhoCentralFoam has no species transport)
  * inviscid (laminar, mu=0) by default; afterburning/chemistry not modelled
  * nozzle interior not meshed (exit-plane inflow), lip thickness neglected
"""
from __future__ import annotations

import json
import math
import os
import sys
from dataclasses import dataclass, asdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "physics"))
from aether_physics.atmosphere import atmosphere  # noqa: E402

R_UNIV = 8314.462618

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by Project Aether backend/openfoam/case_generator.py
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    format      ascii;
    class       {cls};
    {loc}object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""


def hdr(obj, cls="dictionary", loc=""):
    return HEADER.format(cls=cls, obj=obj, loc=f'location    "{loc}";\n    ' if loc else "")


@dataclass
class PlumeCase:
    stage: str
    altitude_m: float
    flight_speed_m_s: float
    pe_pa: float
    Te_K: float
    ve_m_s: float
    gamma: float
    mw: float
    exit_radius_m: float
    pa_pa: float
    Ta_K: float
    domain_length_exit_radii: float = 60.0
    domain_radius_exit_radii: float = 20.0
    nx: int = 480
    nr_jet: int = 40
    nr_outer: int = 140
    wedge_deg: float = 2.5
    end_time_s: float = 0.02
    n_procs: int = 8


def from_project(stage="stage1", altitude_m=10000.0, flight_speed_m_s=None):
    """Build a case definition from data/vehicle.json, data/thermo.json and the reference trajectory."""
    cfg = json.load(open(os.path.join(ROOT, "data", "vehicle.json"), encoding="utf-8"))
    th = json.load(open(os.path.join(ROOT, "data", "thermo.json"), encoding="utf-8"))
    e = cfg["engines"][stage]
    s = th["stages"][stage]
    T, P, rho, a = atmosphere(altitude_m)
    if flight_speed_m_s is None:
        ref = json.load(open(os.path.join(ROOT, "data", "reference_trajectory.json"), encoding="utf-8"))
        best = min(ref["samples"], key=lambda r: abs(r["h"] - altitude_m) if r["phase"] in (1, 4) else 1e12)
        flight_speed_m_s = best["v_rel"]
    return PlumeCase(stage=stage, altitude_m=altitude_m, flight_speed_m_s=flight_speed_m_s, pe_pa=e["pe_pa"],
                     Te_K=s["Te_K"], ve_m_s=s["ve_m_s"], gamma=s["gamma_e"], mw=s["mw_c"],
                     exit_radius_m=math.sqrt(e["ae_m2"] / math.pi), pa_pa=P, Ta_K=T)


def _block_mesh(c: PlumeCase) -> str:
    th = math.radians(c.wedge_deg)
    L = c.domain_length_exit_radii * c.exit_radius_m
    R1 = c.exit_radius_m
    R2 = c.domain_radius_exit_radii * c.exit_radius_m
    cy, sz = math.cos(th), math.sin(th)
    # vertices: axis (duplicated for the collapsed wedge edge), jet edge, outer edge, at x=0 and x=L
    v = []
    for x in (0.0, L):
        v += [(x, 0, 0), (x, R1 * cy, -R1 * sz), (x, R2 * cy, -R2 * sz), (x, R1 * cy, R1 * sz), (x, R2 * cy, R2 * sz)]
    # index map: x0: 0 axis, 1 r1-, 2 r2-, 3 r1+, 4 r2+ ; x=L: +5
    vs = "\n".join(f"    ({a:.6g} {b:.6g} {cc:.6g})" for a, b, cc in v)
    g_out = 8.0
    return hdr("blockMeshDict") + f"""
convertToMeters 1;

vertices
(
{vs}
);

blocks
(
    // jet core: axis .. exit radius (wedge, collapsed axis edge)
    hex (0 5 6 1 0 5 8 3) ({c.nx} {c.nr_jet} 1) simpleGrading (4 1 1)
    // ambient: exit radius .. far field
    hex (1 6 7 2 3 8 9 4) ({c.nx} {c.nr_outer} 1) simpleGrading (4 {g_out} 1)
);

boundary
(
    nozzleExit {{ type patch; faces ( (0 1 3 0) ); }}
    coflowInlet {{ type patch; faces ( (1 2 4 3) ); }}
    farField {{ type patch; faces ( (2 7 9 4) ); }}
    outlet {{ type patch; faces ( (5 8 6 5) (6 8 9 7) ); }}
    wedgeMinus {{ type wedge; faces ( (0 5 6 1) (1 6 7 2) ); }}
    wedgePlus {{ type wedge; faces ( (0 3 8 5) (3 4 9 8) ); }}
    axis {{ type empty; faces ( (0 5 5 0) ); }}
);
"""


def _thermo(c: PlumeCase) -> str:
    cp = c.gamma / (c.gamma - 1.0) * R_UNIV / c.mw  # J/kg/K
    return hdr("thermophysicalProperties", loc="constant") + f"""
thermoType
{{
    type            hePsiThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState perfectGas;
    specie          specie;
    energy          sensibleInternalEnergy;
}}

mixture
{{
    // Exhaust products at the nozzle exit (Cantera shifting equilibrium): gamma={c.gamma:.4f}, MW={c.mw:.3f}
    specie         {{ molWeight {c.mw:.4f}; }}
    thermodynamics {{ Cp {cp:.2f}; Hf 0; }}
    transport      {{ mu 0; Pr 1; }}
}}
"""


def _fields(c: PlumeCase) -> dict:
    files = {}
    files["0/p"] = hdr("p", "volScalarField", "0") + f"""
dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform {c.pa_pa:.6g};
boundaryField
{{
    nozzleExit  {{ type fixedValue; value uniform {c.pe_pa:.6g}; }}
    coflowInlet {{ type fixedValue; value uniform {c.pa_pa:.6g}; }}
    farField    {{ type waveTransmissive; field p; psi thermo:psi; gamma {c.gamma:.4f}; fieldInf {c.pa_pa:.6g}; lInf {c.domain_radius_exit_radii * c.exit_radius_m:.3g}; value uniform {c.pa_pa:.6g}; }}
    outlet      {{ type waveTransmissive; field p; psi thermo:psi; gamma {c.gamma:.4f}; fieldInf {c.pa_pa:.6g}; lInf {c.domain_length_exit_radii * c.exit_radius_m:.3g}; value uniform {c.pa_pa:.6g}; }}
    wedgeMinus  {{ type wedge; }}
    wedgePlus   {{ type wedge; }}
    axis        {{ type empty; }}
}}
"""
    files["0/T"] = hdr("T", "volScalarField", "0") + f"""
dimensions      [0 0 0 1 0 0 0];
internalField   uniform {c.Ta_K:.6g};
boundaryField
{{
    nozzleExit  {{ type fixedValue; value uniform {c.Te_K:.6g}; }}
    coflowInlet {{ type fixedValue; value uniform {c.Ta_K:.6g}; }}
    farField    {{ type inletOutlet; inletValue uniform {c.Ta_K:.6g}; value uniform {c.Ta_K:.6g}; }}
    outlet      {{ type zeroGradient; }}
    wedgeMinus  {{ type wedge; }}
    wedgePlus   {{ type wedge; }}
    axis        {{ type empty; }}
}}
"""
    files["0/U"] = hdr("U", "volVectorField", "0") + f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform ({c.flight_speed_m_s:.6g} 0 0);
boundaryField
{{
    nozzleExit  {{ type fixedValue; value uniform ({c.ve_m_s:.6g} 0 0); }}
    coflowInlet {{ type fixedValue; value uniform ({c.flight_speed_m_s:.6g} 0 0); }}
    farField    {{ type inletOutlet; inletValue uniform ({c.flight_speed_m_s:.6g} 0 0); value uniform ({c.flight_speed_m_s:.6g} 0 0); }}
    outlet      {{ type zeroGradient; }}
    wedgeMinus  {{ type wedge; }}
    wedgePlus   {{ type wedge; }}
    axis        {{ type empty; }}
}}
"""
    return files


def _system(c: PlumeCase) -> dict:
    L = c.domain_length_exit_radii * c.exit_radius_m
    f = {}
    f["system/controlDict"] = hdr("controlDict", loc="system") + f"""
application     rhoCentralFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {c.end_time_s:g};
deltaT          1e-8;
writeControl    adjustableRunTime;
writeInterval   {c.end_time_s / 10:g};
purgeWrite      3;
writeFormat     binary;
adjustTimeStep  yes;
maxCo           0.4;
maxDeltaT       1e-5;
functions
{{
    axisProbe
    {{
        type            sets;
        libs            ("libsampling.so");
        writeControl    writeTime;
        interpolationScheme cellPoint;
        setFormat       csv;
        fields          (p T U Ma);
        sets
        (
            axis {{ type lineUniform; axis x; start (0 1e-4 0); end ({L:.6g} 1e-4 0); nPoints 600; }}
        );
    }}
    MachNo {{ type MachNo; libs ("libfieldFunctionObjects.so"); writeControl writeTime; }}
}}
"""
    f["system/fvSchemes"] = hdr("fvSchemes", loc="system") + """
fluxScheme      Kurganov;
ddtSchemes      { default Euler; }
gradSchemes     { default Gauss linear; }
divSchemes      { default none; div(tauMC) Gauss linear; }
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes
{
    default         linear;
    reconstruct(rho) vanLeer;
    reconstruct(U)  vanLeerV;
    reconstruct(T)  vanLeer;
}
snGradSchemes   { default corrected; }
"""
    f["system/fvSolution"] = hdr("fvSolution", loc="system") + """
solvers
{
    "(rho|rhoU|rhoE)" { solver diagonal; }
    U { solver smoothSolver; smoother GaussSeidel; nSweeps 2; tolerance 1e-09; relTol 0.01; }
    e { $U; tolerance 1e-10; relTol 0; }
}
"""
    f["system/decomposeParDict"] = hdr("decomposeParDict", loc="system") + f"""
numberOfSubdomains {c.n_procs};
method          scotch;
"""
    f["system/blockMeshDict"] = _block_mesh(c)
    f["constant/thermophysicalProperties"] = _thermo(c)
    f["constant/momentumTransport"] = hdr("momentumTransport", loc="constant") + "\nsimulationType laminar;\n"
    f["constant/turbulenceProperties"] = hdr("turbulenceProperties", loc="constant") + "\nsimulationType laminar;\n"
    f["Allrun"] = f"""#!/bin/sh
# Project Aether plume case ({c.stage}, h={c.altitude_m:.0f} m). Requires OpenFOAM (ESI v2312+ or Foundation v11).
cd "${{0%/*}}" || exit 1
. ${{WM_PROJECT_DIR:?}}/bin/tools/RunFunctions
runApplication blockMesh
runApplication checkMesh
runApplication decomposePar
runParallel rhoCentralFoam
runApplication reconstructPar -latestTime
touch AETHER_RUN_COMPLETE
"""
    return f


def write_case(c: PlumeCase, out_dir: str) -> list[str]:
    files = {}
    files.update(_system(c))
    files.update(_fields(c))
    files["aether_case.json"] = json.dumps(dict(asdict(c), label="CASE DEFINITION (not solver output)"), indent=2)
    written = []
    for rel, txt in files.items():
        p = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)
        written.append(rel)
    return written


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="stage1")
    ap.add_argument("--alt", type=float, default=10000.0)
    ap.add_argument("--out", default=os.path.join(ROOT, "backend", "openfoam", "cases", "s1_h10km"))
    a = ap.parse_args()
    case = from_project(a.stage, a.alt)
    w = write_case(case, a.out)
    print(f"wrote {len(w)} files to {a.out}")
    print(json.dumps(asdict(case), indent=1))
